#!/usr/bin/env bash
# Idempotent setup of the production VM (Ubuntu 26.04, arm64 or amd64). Run as root:
#
#   scp -r infra root@<vm>:/root/showcase-infra
#   ssh root@<vm> 'DEPLOY_PUBKEY="ssh-ed25519 AAAA… github-actions" bash /root/showcase-infra/scripts/server-setup.sh'
#
# What it does (safe to re-run; never overwrites an existing .env.prod or certificate):
#   1. Docker (official repo), nginx, certbot, git, ufw
#   2. ufw: allow SSH, 80, 443; deny everything else
#   3. user "deploy" (docker group) + checkout of the repo in /srv/showcase
#   4. /srv/showcase/.env.prod with freshly generated secrets (mode 600)
#   5. /usr/local/bin/showcase-deploy + the CI key, restricted to that command
#   6. nginx site + Let's Encrypt certificate (webroot, renewed by certbot.timer)
set -euo pipefail

API_HOST="${API_HOST:-api.2-29-168-64.sslip.io}"
REPO_URL="${REPO_URL:-https://github.com/aghabekyan101214/vitemarket.git}"
APP_DIR=/srv/showcase
DEPLOY_USER=deploy
INFRA="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
export DEBIAN_FRONTEND=noninteractive

log() { printf '\n==> %s\n' "$*"; }

log "packages"
apt-get update -qq
apt-get install -y -qq ca-certificates curl git ufw nginx certbot >/dev/null
if ! command -v docker >/dev/null; then
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >/dev/null
fi
systemctl enable --now docker >/dev/null

log "firewall"
ufw allow OpenSSH >/dev/null
ufw allow "Nginx Full" >/dev/null
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw --force enable >/dev/null

log "deploy user and checkout"
id "$DEPLOY_USER" >/dev/null 2>&1 || useradd --create-home --shell /bin/bash "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
install -d -o "$DEPLOY_USER" -g "$DEPLOY_USER" -m 755 "$APP_DIR"
if [[ ! -d "$APP_DIR/.git" ]]; then
  sudo -u "$DEPLOY_USER" git clone --quiet "$REPO_URL" "$APP_DIR"
fi

log ".env.prod"
if [[ ! -f "$APP_DIR/.env.prod" ]]; then
  account_id="${CF_ACCOUNT_ID:-c660687e561aa09437a92dda66bfc5f7}"
  umask 077
  cat > "$APP_DIR/.env.prod" <<EOF
# Generated by infra/scripts/server-setup.sh on $(date -u +%F). Never commit. Template: .env.prod.example

# --- image (API_TAG is set by deploy.sh) ---
API_IMAGE=ghcr.io/aghabekyan101214/showcase-api
API_TAG=main

# --- app ---
LOG_LEVEL=INFO
LOG_FORMAT=json
JWT_SECRET=$(openssl rand -hex 32)
JWT_ACCESS_TTL_MINUTES=30
CORS_ALLOW_ORIGINS=
DOCS_ENABLED=true
MAX_REQUEST_BYTES=1048576
LOGIN_RATE_LIMIT_PER_MINUTE=10
DB_POOL_SIZE=10
DB_MAX_OVERFLOW=5

# --- postgres ---
POSTGRES_USER=showcase
POSTGRES_PASSWORD=$(openssl rand -hex 24)
POSTGRES_DB=showcase

# --- Cloudflare R2 (bucket showcase-media) ---
STORAGE_ENDPOINT_URL=https://${account_id}.r2.cloudflarestorage.com
STORAGE_REGION=auto
# R2 API token (Object Read & Write, bucket showcase-media only). Fill in by hand.
STORAGE_ACCESS_KEY_ID=CHANGE_ME
STORAGE_SECRET_ACCESS_KEY=CHANGE_ME
STORAGE_BUCKET=showcase-media
# Public bucket URL (r2.dev until a media domain exists). Fill in by hand.
STORAGE_PUBLIC_BASE_URL=CHANGE_ME
# Transformations need a Cloudflare zone; none yet.
IMAGE_TRANSFORM_PROVIDER=none
UPLOAD_MAX_BYTES=10485760
MEDIA_RETENTION_DAYS=7
MEDIA_GC_INTERVAL_SECONDS=3600

# --- publishing ---
REVALIDATE_WEBHOOK_URL=https://showcase-frontend.quiet-recipe-abf9.workers.dev/api/revalidate
# Same value must be set as the frontend Worker secret REVALIDATE_WEBHOOK_SECRET.
REVALIDATE_WEBHOOK_SECRET=$(openssl rand -hex 32)
PUBLISH_DEBOUNCE_SECONDS=30
CDN_PURGE_PROVIDER=none
CLOUDFLARE_API_TOKEN=

# --- tunnel (unused: host nginx; see docker-compose.prod.yml) ---
CLOUDFLARE_TUNNEL_TOKEN=
EOF
  chown "$DEPLOY_USER:$DEPLOY_USER" "$APP_DIR/.env.prod"
  chmod 600 "$APP_DIR/.env.prod"
  umask 022
else
  echo "exists, left untouched"
fi

log "deploy command and CI key"
install -m 755 "$INFRA/scripts/showcase-deploy" /usr/local/bin/showcase-deploy
home="$(getent passwd "$DEPLOY_USER" | cut -d: -f6)"
install -d -o "$DEPLOY_USER" -g "$DEPLOY_USER" -m 700 "$home/.ssh"
touch "$home/.ssh/authorized_keys"
if [[ -n "${DEPLOY_PUBKEY:-}" ]] && ! grep -qF "$DEPLOY_PUBKEY" "$home/.ssh/authorized_keys"; then
  echo "command=\"/usr/local/bin/showcase-deploy\",restrict $DEPLOY_PUBKEY" >> "$home/.ssh/authorized_keys"
fi
chown "$DEPLOY_USER:$DEPLOY_USER" "$home/.ssh/authorized_keys"
chmod 600 "$home/.ssh/authorized_keys"

log "nginx + TLS for $API_HOST"
install -d -m 755 /var/www/certbot
rm -f /etc/nginx/sites-enabled/default
conf=/etc/nginx/sites-available/showcase-api
if [[ ! -f "/etc/letsencrypt/live/$API_HOST/fullchain.pem" ]]; then
  # Bootstrap: HTTP only, so certbot can answer the challenge.
  cat > "$conf" <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name $API_HOST;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 503; }
}
EOF
  ln -sf "$conf" /etc/nginx/sites-enabled/showcase-api
  nginx -t -q && systemctl reload nginx
  certbot certonly --webroot -w /var/www/certbot -d "$API_HOST" \
    --non-interactive --agree-tos --register-unsafely-without-email
fi
install -m 644 "$INFRA/nginx/showcase-api.conf" "$conf"
ln -sf "$conf" /etc/nginx/sites-enabled/showcase-api
install -d -m 755 /etc/letsencrypt/renewal-hooks/deploy
printf '#!/bin/sh\nsystemctl reload nginx\n' > /etc/letsencrypt/renewal-hooks/deploy/reload-nginx
chmod 755 /etc/letsencrypt/renewal-hooks/deploy/reload-nginx
nginx -t -q && systemctl reload nginx
systemctl enable --now certbot.timer >/dev/null

log "done"
echo "Next: fill the CHANGE_ME values in $APP_DIR/.env.prod, then deploy a tag via CI."
