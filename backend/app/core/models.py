"""SQLAlchemy declarative base and column helpers shared by every module's models."""

import enum
import uuid
from datetime import datetime

from sqlalchemy import DateTime, Enum, MetaData, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.locale import LOCALE_PATTERN

# Deterministic constraint names → stable Alembic autogenerate diffs and readable 409 errors.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# SQL fragment for CHECK constraints on locale columns (same rule as app.core.locale).
LOCALE_CHECK_REGEX = LOCALE_PATTERN


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class TimestampMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUIDv7 primary key generated by Postgres 18 (time-ordered → index friendly)."""
    return mapped_column(primary_key=True, server_default=text("uuidv7()"))


def pg_enum[E: enum.Enum](enum_cls: type[E], name: str) -> Enum:
    """Native Postgres ENUM storing the Python enum *values* (not member names)."""
    return Enum(
        enum_cls,
        name=name,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )
